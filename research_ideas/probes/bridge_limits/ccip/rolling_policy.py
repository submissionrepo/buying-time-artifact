"""Rolling recalibration of detection-matched buckets on CCIP token-lanes (2026-10-16).

Policy (D, m, L, S): every S days, fit the bucket min_r [B(r) + r D] on the trailing L
days of the lane's outbound transfers, multiply its capacity and refill by the margin
m, and apply it to the next S days.  Each S-day segment is replayed FIFO with the
bucket full at the segment start (slightly favourable to the policy).  The first
segment starts once L days of history exist.

Reported per lane and pooled: delayed share of value, delayed transfers, value-weighted
mean delay, and the time-average of the policy's response beta(D) relative to the
bucket at access.  Parameters: D in {1 h, 6 h}, m in {1, 1.5, 2}, L = 90 d, S = 30 d.
"""
from __future__ import annotations

import json
import math
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
import analysis_core as ac  # noqa: E402

DAY = 86400.0
L, S = 90 * DAY, 30 * DAY


def run_lane(times, vals, D, m, cur=None):
    t0, t_end = times[0], times[-1]
    start = t0 + L
    tot = dl_v = dl_n = 0.0
    wdelay = 0.0
    betas = []
    cur_dl_v = cur_dl_n = 0.0
    seg_start = start
    while seg_start < t_end:
        seg_end = seg_start + S
        fit = [(t, v) for t, v in zip(times, vals) if seg_start - L <= t < seg_start]
        test = [(t, v) for t, v in zip(times, vals) if seg_start <= t < seg_end]
        if fit and test:
            ft, fv = zip(*fit)
            b, r, val = ac.best_bucket_exact(list(ft), list(fv), D)
            b, r = m * b, m * r
            tt, tv = zip(*test)
            st = ac.token_bucket_fifo(list(tt), list(tv), b * (1 + 1e-9) + 1e-6, r)
            if cur is not None and cur.get("enabled"):
                cst = ac.token_bucket_fifo(list(tt), list(tv), cur["b"] * (1 + 1e-9) + 1e-6, cur["r"])
                cur_dl_v += cst.delayed_value
                cur_dl_n += cst.delayed_count
            tot += sum(tv)
            dl_v += st.delayed_value
            dl_n += st.delayed_count
            wdelay += st.value_weighted_delay * sum(tv)
            betas.append(b + r * D)
        seg_start = seg_end
    return {"test_value": tot, "delayed_share": dl_v / tot if tot else math.nan, "delayed_n": int(dl_n),
            "current_delayed_share": (cur_dl_v / tot) if (tot and cur is not None and cur.get("enabled")) else math.nan,
            "current_delayed_n": int(cur_dl_n),
            "mean_delay_h": (wdelay / tot / 3600.0) if tot else math.nan,
            "mean_beta": sum(betas) / len(betas) if betas else math.nan, "segments": len(betas)}


def main():
    fr = json.load(open(os.path.join(ROOT, "data", "ccip", "derived", "flows_results.json"), encoding="utf-8"))
    tr = pd.read_csv(os.path.join(ROOT, "data", "ccip", "derived", "transfers.csv.gz"),
                     usecols=["message_id", "src", "dst", "token", "amount", "send_ts"]).drop_duplicates("message_id")
    out = []
    for lane in fr["results"]:
        sub = tr[(tr.src == lane["src"]) & (tr.dst == lane["dst"]) & (tr.token == lane["token"])].sort_values("send_ts")
        if len(sub) < 50:
            continue
        times = sub.send_ts.astype(float).tolist()
        vals = sub.amount.astype(float).tolist()
        if times[-1] - times[0] < L + S:
            continue
        price = (lane.get("price") or {}).get("now_usd") or float("nan")
        cur = (lane.get("current_bucket") or {}).get("out") or {}
        rec = {"lane": (lane.get("lane") or f"{lane['token']} {lane['src']} -> {lane['dst']}"), "price_usd": price}
        for D_name, D in (("1 h", 3600.0), ("6 h", 21600.0)):
            for m in (1.0, 1.5, 2.0):
                res = run_lane(times, vals, D, m, cur)
                res["current_beta"] = (cur.get("b", 0) + cur.get("r", 0) * D) if cur.get("enabled") else math.nan
                rec[f"{D_name} m={m}"] = res
        out.append(rec)
    json.dump(out, open(os.path.join(ROOT, "data", "ccip", "derived", "rolling_policy.json"), "w", encoding="utf-8"), indent=1)
    lines = ["# CCIP: rolling recalibration of detection-matched buckets (generated)", "",
             "Generated by `ccip/rolling_policy.py`. Every 30 days the bucket min_r [B(r) + r D] is refitted on the trailing 90 days "
             "and scaled by the margin m; each 30-day segment is replayed FIFO from a full bucket. Pooled delayed share = delayed value "
             "over tested value across lanes (USD at current prices). Mean beta = time-average of the policy's response at D; "
             "ratio = mean beta over the response of the bucket at access (lanes with a bucket).", "",
             "| policy | lanes | pooled delayed share | delayed transfers | median lane delayed share | median mean beta / current beta | bucket at access, same segments: pooled delayed share (lanes with a bucket) |",
             "|---|---|---|---|---|---|---|"]
    for key in [f"{d} m={m}" for d in ("1 h", "6 h") for m in (1.0, 1.5, 2.0)]:
        tv = sum(r[key]["test_value"] * r["price_usd"] for r in out)
        dv = sum(r[key]["delayed_share"] * r[key]["test_value"] * r["price_usd"] for r in out if not math.isnan(r[key]["delayed_share"]))
        dn = sum(r[key]["delayed_n"] for r in out)
        shares = sorted(r[key]["delayed_share"] for r in out if not math.isnan(r[key]["delayed_share"]))
        ratios = sorted(r[key]["mean_beta"] / r[key]["current_beta"] for r in out
                        if not math.isnan(r[key]["current_beta"]) and r[key]["current_beta"] > 0 and not math.isnan(r[key]["mean_beta"]))
        med = lambda xs: xs[len(xs) // 2] if xs else math.nan
        withb = [r for r in out if not math.isnan(r[key]["current_delayed_share"])]
        tvb = sum(r[key]["test_value"] * r["price_usd"] for r in withb)
        cdv = sum(r[key]["current_delayed_share"] * r[key]["test_value"] * r["price_usd"] for r in withb)
        pdv = sum(r[key]["delayed_share"] * r[key]["test_value"] * r["price_usd"] for r in withb)
        lines.append(f"| D = {key} | {len(out)} | {dv / tv:.3f} (lanes with a bucket: {pdv / tvb:.3f}) | {dn} | {med(shares):.3f} | {med(ratios):.2f} | {cdv / tvb:.3f} |")
    lines += ["", "Per lane (delayed share; mean beta / current beta):", "", "| token-lane | 1 h m=1.5 | 6 h m=1.5 | 6 h m=2 |", "|---|---|---|---|"]
    for r in out:
        cells = []
        for key in ("1 h m=1.5", "6 h m=1.5", "6 h m=2.0"):
            x = r[key]
            ratio = x["mean_beta"] / x["current_beta"] if not math.isnan(x["current_beta"]) and x["current_beta"] > 0 else math.nan
            cells.append(f"{x['delayed_share']:.3f}; {ratio:.2f}")
        lines.append(f"| {r['lane']} | " + " | ".join(cells) + " |")
    open(os.path.join(ROOT, "results", "ccip_rolling_policy.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
