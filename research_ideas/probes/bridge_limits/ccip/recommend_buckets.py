"""Detection-matched buckets for the selected CCIP token-lanes (2026-10-16).

For each selected token-lane (data/ccip/derived/flows_results.json) the empirical
envelope E(u) of the lane's outbound transfers is computed on a fine grid of window
lengths from the per-transfer table (data/ccip/derived/transfers.csv.gz), together
with E(0+) = the largest single transfer.  Proposition 7: among token buckets that
delay no historical transfer, the smallest compromise response at horizon D is
min over r of B(r) + r D, where B(r) is the exact burstiness of the stream at refill
r (analysis_core.burstiness); this equals the upper concave hull of the envelope at D.
The script reports, for D* in {1 h, 6 h}: the hull value, the supporting bucket, the
current outbound bucket's response b + r D*, and their ratio.  Token units throughout;
USD at the current price recorded by the CCIP analysis.  In-sample: the supporting
bucket delays no transfer of the history it was fitted to.
"""
from __future__ import annotations

import json
import math
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
import analysis_core as ac  # noqa: E402

GRID_S = sorted(set([60 * m for m in (1, 2, 5, 10, 20, 30, 45)] + [3600 * h for h in (1, 2, 3, 4, 6, 8, 12, 18, 24, 36, 48, 72, 96, 120, 168)]))
TARGETS = {"1 h": 3600, "6 h": 21600}


def main():
    fr = json.load(open(os.path.join(ROOT, "data", "ccip", "derived", "flows_results.json"), encoding="utf-8"))
    tr = pd.read_csv(os.path.join(ROOT, "data", "ccip", "derived", "transfers.csv.gz"),
                     usecols=["message_id", "src", "dst", "token", "amount", "send_ts"])
    tr = tr.drop_duplicates("message_id")
    rows = []
    for lane in fr["results"]:
        sub = tr[(tr.src == lane["src"]) & (tr.dst == lane["dst"]) & (tr.token == lane["token"])]
        if sub.empty:
            continue
        times = sub.send_ts.astype(float).tolist()
        vals = sub.amount.astype(float).tolist()
        pts = [(0.0, max(vals))] + [(float(u), ac.envelope_events(times, vals, u)) for u in GRID_S]
        price = (lane.get("price") or {}).get("now_usd") or float("nan")
        cur = (lane.get("current_bucket") or {}).get("out") or {}
        rec = {"lane": (lane.get("lane") or f"{lane['token']} {lane['src']} -> {lane['dst']}"), "n": len(vals), "price_usd": price,
               "E0": pts[0][1], "current_enabled": bool(cur.get("enabled")), "current_b": cur.get("b"), "current_r_per_s": cur.get("r")}
        for name, D in TARGETS.items():
            b, r, val = ac.best_bucket_exact(times, vals, float(D))
            E_D = ac.envelope_events(times, vals, float(D))
            cur_beta = (cur.get("b", 0.0) + cur.get("r", 0.0) * D) if cur.get("enabled") else math.inf
            rec[name] = {"E": E_D, "hull": val, "b_star": b, "r_star_per_s": r, "current_beta": cur_beta,
                         "current_over_hull": cur_beta / val if val else math.nan,
                         "hull_over_E": val / E_D if E_D else math.nan}
            # in-sample check: the supporting bucket must delay nothing
            st = ac.token_bucket_fifo(times, vals, b * (1 + 1e-9) + 1e-6, r)
            rec[name]["in_sample_delayed"] = st.delayed_count
        rows.append(rec)
    out = os.path.join(ROOT, "data", "ccip", "derived", "recommended_buckets.json")
    json.dump(rows, open(out, "w", encoding="utf-8"), indent=1)
    lines = ["# CCIP: detection-matched buckets versus buckets in force (generated)", "",
             "Generated by `ccip/recommend_buckets.py`. Outbound transfers of each selected token-lane, full history. "
             "Hull = min over r of B(r) + r D with the exact burstiness B(r) (Proposition 7; equals the upper concave hull of the "
             "envelope at D): the smallest response of any bucket that delays no historical transfer. b* = B(r*), r* = the minimizer. Current = outbound bucket at access (b + r D). "
             "USD at the current price. In-sample: the supporting bucket delays none of the transfers it was fitted to "
             "(column 'delayed' checks this).", "",
             "| token-lane | D | E(D) USD M | hull USD M | b* USD M | r* USD M per h | current beta USD M | current / hull | delayed |",
             "|---|---|---|---|---|---|---|---|---|"]
    for rec in rows:
        p = rec["price_usd"]
        for name in TARGETS:
            x = rec[name]
            cb = "disabled" if not math.isfinite(x["current_beta"]) else f"{x['current_beta']*p/1e6:.2f}"
            ratio = "" if not math.isfinite(x["current_over_hull"]) else f"{x['current_over_hull']:.2f}"
            lines.append(f"| {rec['lane']} | {name} | {x['E']*p/1e6:.2f} | {x['hull']*p/1e6:.2f} | {x['b_star']*p/1e6:.2f} | "
                         f"{x['r_star_per_s']*3600*p/1e6:.3f} | {cb} | {ratio} | {x['in_sample_delayed']} |")
    res = os.path.join(ROOT, "results", "ccip_recommended_buckets.md")
    open(res, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
