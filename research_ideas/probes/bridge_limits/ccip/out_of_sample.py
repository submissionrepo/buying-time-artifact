"""Out-of-sample check of detection-matched buckets on CCIP token-lanes (2026-10-16).

For each selected token-lane, the outbound transfer history is split at the median
transfer (by time).  The bucket min_r [B(r) + r D] is fitted on the first half
(D = 1 h and 6 h) and replayed FIFO on the second half (bucket full at the split).
Reported: delayed transfers and value, value-weighted mean delay and maximum delay on
the second half, the fitted bucket's response at D, and the same statistics for the
bucket at access (the current outbound bucket), so the two can be compared on equal
terms.  Token units; USD at the current price.
"""
from __future__ import annotations

import json
import math
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
import analysis_core as ac  # noqa: E402

TARGETS = {"1 h": 3600.0, "6 h": 21600.0}


def stats(times, vals, b, r):
    st = ac.token_bucket_fifo(times, vals, b, r)
    return {"delayed_n": st.delayed_count, "delayed_value": st.delayed_value,
            "mean_delay_h": st.value_weighted_delay / 3600.0, "max_delay_h": st.max_delay / 3600.0}


def main():
    fr = json.load(open(os.path.join(ROOT, "data", "ccip", "derived", "flows_results.json"), encoding="utf-8"))
    tr = pd.read_csv(os.path.join(ROOT, "data", "ccip", "derived", "transfers.csv.gz"),
                     usecols=["message_id", "src", "dst", "token", "amount", "send_ts"]).drop_duplicates("message_id")
    rows = []
    for lane in fr["results"]:
        sub = tr[(tr.src == lane["src"]) & (tr.dst == lane["dst"]) & (tr.token == lane["token"])].sort_values("send_ts")
        if len(sub) < 20:
            continue
        k = len(sub) // 2
        t1, v1 = sub.send_ts.iloc[:k].astype(float).tolist(), sub.amount.iloc[:k].astype(float).tolist()
        t2, v2 = sub.send_ts.iloc[k:].astype(float).tolist(), sub.amount.iloc[k:].astype(float).tolist()
        price = (lane.get("price") or {}).get("now_usd") or float("nan")
        cur = (lane.get("current_bucket") or {}).get("out") or {}
        rec = {"lane": (lane.get("lane") or f"{lane['token']} {lane['src']} -> {lane['dst']}"), "n_fit": len(t1), "n_test": len(t2),
               "test_value": sum(v2), "price_usd": price}
        if cur.get("enabled"):
            rec["current"] = stats(t2, v2, cur["b"], cur["r"])
            rec["current"]["beta"] = {name: cur["b"] + cur["r"] * D for name, D in TARGETS.items()}
        for name, D in TARGETS.items():
            b, r, val = ac.best_bucket_exact(t1, v1, D)
            rec[name] = {"b": b, "r": r, "beta_fit": val, **stats(t2, v2, b * (1 + 1e-9) + 1e-6, r)}
        rows.append(rec)
    json.dump(rows, open(os.path.join(ROOT, "data", "ccip", "derived", "out_of_sample.json"), "w", encoding="utf-8"), indent=1)
    lines = ["# CCIP: detection-matched buckets out of sample (generated)", "",
             "Generated by `ccip/out_of_sample.py`. Each lane's outbound history split at the median transfer; bucket "
             "min_r [B(r) + r D] fitted on the first half, replayed FIFO on the second half. Current = bucket at access on the "
             "second half. Delayed share = delayed value over second-half value. USD millions at the current price.", "",
             "| token-lane | D | fitted beta(D) | delayed n / share | mean delay h | max delay h | current beta(D) | current delayed n / share |",
             "|---|---|---|---|---|---|---|---|"]
    for rec in rows:
        p = rec["price_usd"]
        for name in TARGETS:
            x = rec[name]
            cur = rec.get("current")
            cb = "disabled" if cur is None else f"{cur['beta'][name]*p/1e6:.2f}"
            cd = "" if cur is None else f"{cur['delayed_n']} / {cur['delayed_value']/rec['test_value']:.3f}"
            lines.append(f"| {rec['lane']} | {name} | {x['beta_fit']*p/1e6:.2f} | {x['delayed_n']} / {x['delayed_value']/rec['test_value']:.3f} | "
                         f"{x['mean_delay_h']:.3f} | {x['max_delay_h']:.1f} | {cb} | {cd} |")
    open(os.path.join(ROOT, "results", "ccip_out_of_sample.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
