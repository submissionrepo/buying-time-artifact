"""How much legitimate value any limit with a given exposure must delay (2026-10-16).

Proposition (delay budget, paper Section 7): let a defense that sees only the amounts and times of
withdrawals let out at most x within any interval of length d. On a legitimate history l, the value it
delays by more than h is at least
    F(x) = max over disjoint intervals I_1, ..., I_m of length d - h of  sum_k (l(I_k) - x)^+ ,
since the arrivals in I_k that wait at most h leave within an interval of length d.

For each failed bridge of the per-bridge aggregate (replay_perbridge.py) and each release contract
("leg"), this script takes the out-of-sample bucket of the paper (fitted to the 90 days that end 30
days before the failure for D_fit = 6 h, margin 1.5) and its release within d = 6 h, x = b + 6 r, and
computes on the 30 days before the failure (the test window of origin 1, and origin 2 the month
before) (a) F(x) with h = 0, the least value any defense that lets out no more than x within six hours
must delay, and (b) the value the bucket itself delays (FIFO fluid bucket, full at the start). It
reports both as shares of the tested legitimate value, summed over legs and failures, and per failure.
F is computed exactly by dynamic programming over windows that start at a transfer (moving a
window's start to its first transfer does not lower its content).

Outputs results/delay_budget.json and results/delay_budget.md. Run with the Python environment of requirements.txt.
"""
from __future__ import annotations

import json
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import replay_perbridge as pb  # noqa: E402

D_FIT = 6 * pb.H
MU = 1.5


def F_lower(t, v, L, x):
    """max over disjoint windows [s, s + L) of sum (content - x)^+, windows starting at transfers."""
    n = len(t)
    if n == 0:
        return 0.0
    cum = np.concatenate([[0.0], np.cumsum(v)])
    nxt = np.searchsorted(t, t + L, side="left")       # first index at or after t_i + L
    f = np.zeros(n + 1)
    for i in range(n - 1, -1, -1):
        w = cum[nxt[i]] - cum[i]
        f[i] = max(f[i + 1], max(0.0, w - x) + f[nxt[i]])
    return float(f[0])


def main():
    inc, cod = pb.load_failures()
    legit_dir = os.path.join(HERE, "data", "legit")
    ids = sorted(f[:-4] for f in os.listdir(legit_dir) if f.endswith(".csv") and f[:-4] in inc
                 and inc[f[:-4]]["response_delay_s"])
    F_all = pb.compute(inc, cod, ids, legit_dir)
    excl = pb.exclusions(F_all)
    agg_ids = [i for i in ids if i not in excl]
    out = {"d_h": D_FIT / pb.H, "margin": MU, "failures": {}, "totals": {}}
    for o, (fwin, twin) in pb.ORIGINS.items():
        tot = {"test_value": 0.0, "lower": 0.0, "bucket_delayed": 0.0}
        for i in agg_ids:
            r = inc[i]
            t_fail = pb.ts(r["first_release_utc"])
            legs, _ = pb.load_history(os.path.join(legit_dir, f"{i}.csv"), t_fail, fid=i)
            rec = out["failures"].setdefault(i, {})
            row = {"test_value": 0.0, "lower": 0.0, "bucket_delayed": 0.0}
            for leg, (t_all, v_all) in legs.items():
                s, bb = pb.fit(t_all, v_all, t_fail, fwin, D_FIT, None, (i, leg, False))
                if bb is None:
                    continue
                b, rr = MU * bb[0], MU * bb[1]
                x = b + rr * D_FIT
                m = (t_all >= t_fail - twin[0]) & (t_all < t_fail - twin[1])
                tt, tv = t_all[m], v_all[m]
                st = pb.test_stats(t_all, v_all, t_fail, twin, math.inf, b, rr)
                row["test_value"] += float(tv.sum())
                row["lower"] += F_lower(tt, tv, D_FIT, x)
                row["bucket_delayed"] += st["delayed_value"]
            rec[o] = row
            for k in tot:
                tot[k] += row[k]
        tot["lower_share"] = tot["lower"] / tot["test_value"]
        tot["bucket_share"] = tot["bucket_delayed"] / tot["test_value"]
        out["totals"][o] = tot
    json.dump(out, open(os.path.join(HERE, "results", "delay_budget.json"), "w", encoding="utf-8"), indent=1)
    L = ["# Delay budget: least legitimate value any limit with the bucket's six-hour release must delay (generated)", "",
         "Generated by `delay_budget.py`; see its docstring.", "",
         "| origin | tested value (M) | lower bound F (share) | bucket delays (share) |", "|---|---|---|---|"]
    for o, tot in out["totals"].items():
        L.append(f"| {o} | {tot['test_value'] / 1e6:,.0f} | {100 * tot['lower_share']:.1f}% | {100 * tot['bucket_share']:.1f}% |")
    L += ["", "| failure | o1 lower | o1 bucket | o2 lower | o2 bucket |", "|---|---|---|---|---|"]
    for i, rec in out["failures"].items():
        cells = []
        for o in pb.ORIGINS:
            row = rec.get(o, {})
            tv = row.get("test_value", 0.0)
            cells += [f"{100 * row['lower'] / tv:.1f}%" if tv else "-", f"{100 * row['bucket_delayed'] / tv:.1f}%" if tv else "-"]
        L.append(f"| {i} | " + " | ".join(cells) + " |")
    open(os.path.join(HERE, "results", "delay_budget.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
