"""Envelopes and the pooling gap on the corrected Wormhole Token Bridge series (2026-10-16).

Replaces the pooling and envelope numbers that `envelopes_and_usage.py` computed from the
raw Portal series, which includes CCTP v2 transfers (66% of the last 365 days) that the
Governor does not meter.  Inputs, written by the per-transfer pipeline:
  data/wormhole/flows/series_full_hourly.csv   hour_utc, chain_id, usd  (Portal minus CCTP v2,
                                               minus the documented 2022-02-02 event transfers)
  data/wormhole/flows/series_small_hourly.csv  the same below the big-transfer size in force
Output: results/wormhole_pooling_clean.md (tables), data/wormhole/derived/pooling_clean.json.
"""
from __future__ import annotations

import csv
import json
import os
from collections import defaultdict
from datetime import datetime, timedelta, timezone

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FLOWS = os.path.join(ROOT, "data", "wormhole", "flows")
CHAINS = {1: "Solana", 2: "Ethereum", 4: "BSC", 5: "Polygon", 6: "Avalanche",
          21: "Sui", 22: "Aptos", 23: "Arbitrum", 30: "Base"}
END = datetime(2026, 10, 15, 16, tzinfo=timezone.utc)
PERIODS = {"12 months": END - timedelta(days=365), "24 months": END - timedelta(days=730)}
WINDOWS = [1, 2, 3, 6, 12, 24, 48, 72, 168]


def load(name):
    series = defaultdict(dict)
    with open(os.path.join(FLOWS, name), encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            t = datetime.fromisoformat(row["hour_utc"].replace("Z", "+00:00"))
            series[int(row["chain_id"])][t] = series[int(row["chain_id"])].get(t, 0.0) + float(row["usd"])
    return series


def dense(points, start, end):
    n = int((end - start).total_seconds() // 3600)
    arr = np.zeros(n)
    for t, v in points.items():
        k = int((t - start).total_seconds() // 3600)
        if 0 <= k < n:
            arr[k] += v
    return arr


def rolling_max(arr, k):
    c = np.concatenate([[0.0], np.cumsum(arr)])
    return float((c[k:] - c[:-k]).max()) if len(arr) >= k else float(arr.sum())


def main():
    out = {}
    lines = ["# Wormhole Token Bridge: envelopes and the pooling gap on the corrected series (generated)", "",
             "Generated by `wormhole/pooling_clean.py` from `data/wormhole/flows/series_full_hourly.csv` (Portal minus CCTP v2, "
             "minus the 2022-02-02 event transfers) and `series_small_hourly.csv` (below the big-transfer size in force). Nine main "
             "chains. USD millions. E(k) = max over start hours of the value leaving within k hours. Pooling ratio = envelope of the "
             "summed flow over the sum of the chain envelopes (Proposition 4).", ""]
    for series_name in ("series_full_hourly.csv", "series_small_hourly.csv"):
        s = load(series_name)
        for pname, start in PERIODS.items():
            arrs = {c: dense(s.get(c, {}), start, END) for c in CHAINS}
            tot = sum(arrs.values())
            rec = {"per_chain": {}, "sum": {}, "pooling": {}}
            for c, name in CHAINS.items():
                rec["per_chain"][name] = {str(k): rolling_max(arrs[c], k) for k in WINDOWS}
            for k in WINDOWS:
                sep = sum(rec["per_chain"][CHAINS[c]][str(k)] for c in CHAINS)
                pooled = rolling_max(tot, k)
                rec["sum"][str(k)] = pooled
                rec["pooling"][str(k)] = {"sum_of_chain_envelopes": sep, "envelope_of_sum": pooled, "ratio": pooled / sep if sep else float("nan")}
            out[f"{series_name}|{pname}"] = rec
            label = "full series" if "full" in series_name else "below-big series"
            lines += [f"## {label}, {pname}", "", "| chain | E(1h) | E(6h) | E(24h) | E(7d) |", "|---|---|---|---|---|"]
            for c, name in CHAINS.items():
                e = rec["per_chain"][name]
                lines.append(f"| {name} | {e['1']/1e6:.2f} | {e['6']/1e6:.2f} | {e['24']/1e6:.2f} | {e['168']/1e6:.2f} |")
            e = rec["sum"]
            lines.append(f"| all nine | {e['1']/1e6:.2f} | {e['6']/1e6:.2f} | {e['24']/1e6:.2f} | {e['168']/1e6:.2f} |")
            lines += ["", "| k hours | sum of chain envelopes | envelope of sum | ratio |", "|---|---|---|---|"]
            for k in WINDOWS:
                p = rec["pooling"][str(k)]
                lines.append(f"| {k} | {p['sum_of_chain_envelopes']/1e6:.2f} | {p['envelope_of_sum']/1e6:.2f} | {p['ratio']:.3f} |")
            lines.append("")
    os.makedirs(os.path.join(ROOT, "data", "wormhole", "derived"), exist_ok=True)
    json.dump(out, open(os.path.join(ROOT, "data", "wormhole", "derived", "pooling_clean.json"), "w", encoding="utf-8"), indent=1)
    open(os.path.join(ROOT, "results", "wormhole_pooling_clean.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
